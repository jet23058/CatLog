// 產生 / 檢查 packages/core/fixtures/cloud-storage-v3.json：
// 用 web 實際的 writeCloudData 寫出一份雲端資料，iOS（CatLogKit）的測試會讀同一個檔案，
// 確認 iOS 讀得懂 web 寫的格式。更新格式後執行 `UPDATE_FIXTURES=1 npm run test:run -w @catlog/web`。
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, beforeEach, expect, test, vi } from 'vitest';

const store = vi.hoisted(() => ({ docs: new Map() }));

vi.mock('firebase/firestore', () => {
    const pathOf = (...segments) => segments.filter((s) => typeof s === 'string').join('/');
    const makeSnapshot = (p) => ({ id: p.split('/').pop(), exists: () => store.docs.has(p), data: () => store.docs.get(p) });
    return {
        collection: (_db, ...segments) => ({ path: pathOf(...segments) }),
        doc: (parent, ...segments) => ({ path: parent?.path ? pathOf(parent.path, ...segments) : pathOf(...segments) }),
        getDoc: async (ref) => makeSnapshot(ref.path),
        setDoc: async (ref, value) => { store.docs.set(ref.path, value); },
        where: () => ({}), orderBy: () => ({}), query: () => ({}), getDocs: async () => ({ docs: [] }),
        runTransaction: async (_db, fn) => fn({
            get: async (ref) => makeSnapshot(ref.path),
            set: (ref, value) => store.docs.set(ref.path, value)
        }),
        writeBatch: () => {
            const sets = [];
            return { set: (ref, value) => sets.push([ref.path, value]), delete: () => {}, commit: async () => sets.forEach(([p, v]) => store.docs.set(p, v)) };
        }
    };
});

import { writeCloudData } from './cloudStorage';

const fixturePath = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../packages/core/fixtures/cloud-storage-v3.json');

// 含中文、emoji（surrogate pair）與未知欄位；chunkSize 調小以產生多個資料塊，並讓切點落在 emoji 上。
export const FIXTURE_DATA = {
    schemaVersion: 1,
    records: { '2026-03-31': [{ name: '銀行存款', type: 'fixed', amount: 1234567 }] },
    memos: { '2026-03-31': '加薪了 🎉🐱' },
    incomes: { '2026-03': { totalAmount: 150000, sources: [{ company: '公司', amount: 150000 }] } },
    expenses: {}, debts: {}, debtEvents: {}, stockTransactions: [], stockHoldingSnapshots: {},
    fireSettings: { withdrawalRate: 4 },
    futureField: { keep: true }
};

beforeEach(() => {
    store.docs.clear();
    vi.spyOn(Date, 'now').mockReturnValue(1767225600000);
    vi.spyOn(Math, 'random').mockReturnValue(0.5);
});
afterEach(() => vi.restoreAllMocks());

test('web writer output matches the shared iOS fixture', async () => {
    await writeCloudData({}, 'fixture-user', FIXTURE_DATA, { expectedRevision: 0, deviceId: 'web-fixture', chunkSize: 37 });
    const docs = Object.fromEntries([...store.docs.entries()].sort(([a], [b]) => a.localeCompare(b)));
    const fixture = { description: 'Generated by apps/web/src/cloudStorage.fixture.test.js — do not edit by hand.', data: FIXTURE_DATA, docs };
    const text = `${JSON.stringify(fixture, null, 2)}\n`;

    if (process.env.UPDATE_FIXTURES || !fs.existsSync(fixturePath)) fs.writeFileSync(fixturePath, text);
    expect(fs.readFileSync(fixturePath, 'utf8')).toBe(text);
    expect(Object.keys(docs).filter((k) => k.includes('/chunks/')).length).toBeGreaterThan(3);
});
